import fs from "node:fs";
import path from "node:path";
import { AGENT_SPECS, shimNames, type Agent } from "./agents.ts";
import { agentDir, shimsDir } from "./paths.ts";

/**
 * Resolve a command on PATH, skipping tread's own shim directory so a shim
 * never re-execs itself.
 */
export function realBinary(name: string): string | null {
  const shims = shimsDir();
  for (const dir of (process.env.PATH ?? "").split(":")) {
    if (!dir || path.resolve(dir) === path.resolve(shims)) continue;
    const p = path.join(dir, name);
    try {
      fs.accessSync(p, fs.constants.X_OK);
      if (fs.statSync(p).isFile() || fs.lstatSync(p).isSymbolicLink()) return p;
    } catch {}
  }
  return null;
}

function script(name: string, agent: Agent, real: string | null): string {
  const spec = AGENT_SPECS[agent];
  const lines = [
    "#!/bin/sh",
    "# generated by tread — regenerate with `tread doctor --fix`",
    "",
    "# resolve the real binary, ignoring this shim directory",
    `real=${real ? JSON.stringify(real) : '""'}`,
    'if [ ! -x "$real" ]; then',
    `  real=$(PATH=$(printf '%s' "$PATH" | tr ':' '\\n' | grep -vxF "$(dirname "$0")" | paste -sd: -) command -v ${name})`,
    "fi",
    'if [ -z "$real" ]; then',
    `  echo "tread: cannot find the real ${name} on PATH" >&2`,
    "  exit 127",
    "fi",
    "",
    "# outside an environment, behave exactly like the real thing",
    'if [ -z "${TREAD_ENV_DIR:-}" ]; then',
    '  exec "$real" "$@"',
    "fi",
    "",
  ];

  if (spec.needsHome) {
    lines.push(
      "# this agent resolves part of its config through $HOME, so the env dir",
      "# has to become HOME for the agent process only",
      'HOME="$TREAD_ENV_DIR"',
      "export HOME",
      "",
    );
  }
  for (const key of Object.keys(spec.envVars("X"))) {
    lines.push(`${key}="$TREAD_ENV_DIR/${spec.dir}"`, `export ${key}`);
  }
  lines.push("", 'exec "$real" "$@"', "");
  return lines.join("\n");
}

/** (Re)generate every shim. Idempotent. */
export function writeShims(): string[] {
  const dir = shimsDir();
  fs.mkdirSync(dir, { recursive: true });
  const written: string[] = [];
  for (const { name, agent } of shimNames()) {
    const target = path.join(dir, name);
    const body = script(name, agent, realBinary(name));
    const existing = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;
    if (existing !== body) {
      fs.writeFileSync(target, body, { mode: 0o755 });
      written.push(name);
    }
    fs.chmodSync(target, 0o755);
  }
  return written;
}

/** True when every shim exists and still points at a live binary. */
export function shimsHealthy(): boolean {
  const dir = shimsDir();
  for (const { name } of shimNames()) {
    const p = path.join(dir, name);
    if (!fs.existsSync(p)) return false;
    const body = fs.readFileSync(p, "utf8");
    const m = body.match(/^real="(.*)"$/m);
    if (m && m[1] && !fs.existsSync(m[1])) return false;
  }
  return true;
}

export { agentDir };
